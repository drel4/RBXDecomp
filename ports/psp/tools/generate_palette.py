"""Keep PSP colors synchronized with the original engine table."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[3]
source=(root/'Client/App/v8datamodel/BrickColor.cpp').read_text()
rows=re.findall(r'insert\(lego_(\d+),\s*(\d+),\s*(\d+),\s*(\d+),',source)
assert len(rows)>50
out=Path(__file__).resolve().parents[1]/'brick_colors.inc'
out.write_text('// Generated by tools/generate_palette.py from Client/App/v8datamodel/BrickColor.cpp\n'+''.join('    {'+', '.join(r)+'},\n' for r in rows))
print(f'{len(rows)} original BrickColors written to {out}')
